// Generates src/styles/dark-diagrams.css: a dark-theme colour for every colour
// used inside the SVG diagrams. Run after changing diagram colours:
//   node scripts/generate-dark-diagrams.mjs
//
// Each light colour keeps its hue. Pale surfaces become raised dark surfaces,
// outlines become bright lines, strong accents stay vivid and ink becomes light.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const jsxFiles = ["PrecisionScene", "ServiceScene", "PageScene", "RagScene", "IsoParts"].map(name => `src/components/MotionDiagram/${name}.jsx`).concat("src/components/ApproachSection/ApproachGlyph.jsx");
const cssFiles = ["PrecisionScene", "ServiceScene", "PageScene", "RagScene", "MotionDiagram"].map(name => `src/components/MotionDiagram/${name}.css`).concat("src/components/ApproachSection/ApproachSection.css");
const scope = ':is(.precision-scene,.service-figure,.page-scene,.rag-frame,.approach-glyph)';

function parse(hex) {
  let h = hex.replace("#", "");
  if (h === "white") h = "ffffff";
  if (h.length === 3) h = [...h].map(c => c + c).join("");
  const [r, g, b] = [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16) / 255);
  const alpha = h.length === 8 ? h.slice(6) : "";
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  let s = 0, hue = 140;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    hue = max === r ? ((g - b) / d + (g < b ? 6 : 0)) * 60 : max === g ? ((b - r) / d + 2) * 60 : ((r - g) / d + 4) * 60;
  }
  return { h: hue, s, l, alpha };
}

function format({ h, s, l, alpha }) {
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1))));
  return "#" + [f(0), f(8), f(4)].map(v => v.toString(16).padStart(2, "0")).join("") + alpha;
}

const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));

function surface(c) {
  const { l } = c; let { s, h } = c;
  if (s < 0.06) { h = 140; s = 0.1; }
  if (s > 0.5 && l >= 0.5 && l < 0.8) return accent(c);
  if (l >= 0.93) return { ...c, h, s: clamp(s * 0.8, 0.1, 0.32), l: 0.135 + (1 - l) * 0.5 };
  if (l >= 0.7 && s > 0.5) return { ...c, h, s: clamp(s * 0.7, 0.3, 0.55), l: 0.2 + (0.93 - l) * 0.75 };
  if (l >= 0.8) return { ...c, h, s: clamp(s * 0.6, 0.16, 0.45), l: 0.17 + (0.93 - l) * 0.6 };
  if (l >= 0.6) return s > 0.45 ? { ...c, h, s: Math.min(s, 0.75), l: 0.42 + (l - 0.6) * 0.3 } : { ...c, h, s: s * 0.6, l: 0.3 };
  if (l >= 0.45) return { ...c, h, l: l * 0.85 };
  return { ...c, h, s: Math.min(s, 0.35), l: 0.78 - l * 0.3 };
}

// Signal colours (moving packets, checks, highlights) stay bright on dark.
function accent(c) {
  return { ...c, s: clamp(c.s, 0.5, 0.78), l: 0.55 };
}

function line(c) {
  const { l } = c; let { s, h } = c;
  if (s < 0.06) { h = 140; s = 0.08; }
  if (l >= 0.97) return { ...c, h, s: 0.3, l: 0.9 };
  if (l >= 0.8) return { ...c, h, s: Math.min(s, 0.25), l: 0.2 + (1 - l) * 0.4 };
  if (l >= 0.55) return { ...c, h, s: Math.min(s * 0.9, 0.4), l: 0.62 - (l - 0.55) * 0.6 };
  return { ...c, h, s: Math.min(s, 0.45), l: 0.8 - l * 0.25 };
}

function ink(c) {
  return { ...c, s: Math.min(c.s, 0.3), l: c.l < 0.5 ? 0.82 - c.l * 0.2 : c.l < 0.68 ? 0.6 : 0.5 };
}

const out = ["/* Generated by scripts/generate-dark-diagrams.mjs. Do not edit by hand. */"];

// 1. Presentation attributes written in the JSX.
const colours = new Set();
for (const file of jsxFiles) for (const [, hex] of read(file).matchAll(/"(#[0-9a-fA-F]{3,8}|white)"/g)) colours.add(hex);
for (const hex of [...colours].sort()) {
  const c = parse(hex);
  out.push(`[data-theme="dark"] ${scope} [fill="${hex}"] {fill:${format(surface(c))};}`);
  out.push(`[data-theme="dark"] ${scope} [stroke="${hex}"] {stroke:${format(line(c))};}`);
}

// 2. Colours set by diagram stylesheets (classes and custom properties).
const roles = { "--figure-color": accent, "--figure-fill": surface, "--figure-tint": surface, "--figure-stroke": line, "--diagram-accent": accent, "--scene-accent": accent, "--scene-grid": line, "--scene-route": line, "--scene-stroke": line, "--scene-ink-soft": line };
for (const file of cssFiles) {
  const css = read(file).replace(/\/\*[\s\S]*?\*\//g, "").replace(/@media[^{]*\{/g, "").replace(/@keyframes[^{]*\{[^{}]*(\{[^}]*\}[^{}]*)*\}/g, "");
  for (const [, selectorText, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selectors = selectorText.split(",").map(s => s.trim()).filter(s => s && !s.startsWith(":root") && !s.startsWith("[data-theme"));
    if (!selectors.length) continue;
    const decls = [];
    for (const [, prop, hex, important] of body.matchAll(/(fill|stroke|color|--[\w-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*(!important)?/g)) {
      const isText = /text|label|tspan|__note|__index|scene-micro/.test(selectorText);
      const map = prop === "fill" ? (isText ? ink : surface) : prop === "stroke" ? line : prop === "color" ? line : roles[prop];
      if (map) decls.push(`${prop}:${format(map(parse(hex)))}${important ? "!important" : ""}`);
    }
    if (decls.length) out.push(`${selectors.map(s => `[data-theme="dark"] ${s}`).join(",")} {${decls.join(";")};}`);
  }
}

writeFileSync(new URL("src/styles/dark-diagrams.css", root), out.join("\n") + "\n");
console.log(`dark-diagrams.css: ${out.length - 1} rules`);
